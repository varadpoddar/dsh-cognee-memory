import { execFileSync } from 'node:child_process'
import { readFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import vm from 'node:vm'
import { beforeAll, describe, expect, it } from 'vitest'
import { buildBundle, validateBundle } from '../scripts/build-client.mjs'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const OUTPUT = join(ROOT, 'lib', 'client.js')
const SOURCE = join(ROOT, 'src', 'client', 'index.js')

interface CapturedDefinition {
  id?: string
  kind?: string
  title?: () => string
  priority?: string
  guide?: ReadonlyArray<{ id: string; order: number; title: () => string }>
}

interface SlotRegistration {
  options: { name?: string; key?: string }
  component: unknown
}

let exported: {
  apply: (ctx: unknown) => void
  inject: string[]
}

let tabDefinitions: CapturedDefinition[]
let slotRegistrations: SlotRegistration[]
let effects: Array<() => void>

function loadBundle(): typeof exported {
  let captured: { id: string; factory: (require: (name: string) => unknown) => typeof exported } | undefined
  const context = {
    window: {
      __ModuleLoader__: {
        load(definition: typeof captured) {
          captured = definition
        },
      },
    },
    TextEncoder,
    Date,
    URL,
    encodeURIComponent,
    Number,
    Object,
    Array,
    Set,
    Map,
    Error,
    TypeError,
  }
  vm.runInNewContext(readFileSync(OUTPUT, 'utf8'), context, { timeout: 5_000 })
  if (captured === undefined) throw new Error('bundle did not register')
  const react = { createElement: () => null, useState: (v: unknown) => [v, () => {}], useCallback: (fn: unknown) => fn, useEffect: () => {} }
  return captured.factory(() => react)
}

beforeAll(() => {
  execFileSync(process.execPath, [join(ROOT, 'scripts', 'build-client.mjs')], { cwd: ROOT })
  exported = loadBundle()
  tabDefinitions = []
  slotRegistrations = []
  effects = []
  const ctx = {
    effect: (execute: () => (() => void) | void) => {
      const disposer = execute()
      if (typeof disposer === 'function') effects.push(disposer)
      return () => {}
    },
    sidebarRightTabs: {
      register: (definition: CapturedDefinition) => {
        tabDefinitions.push(definition)
        return () => {}
      },
    },
    slots: {
      inject: (_key: string, callback: () => unknown) => callback(),
      register: (options: SlotRegistration['options'], component: unknown) => {
        slotRegistrations.push({ options, component })
        return () => {}
      },
    },
  }
  exported.apply(ctx)
})

describe('client bundle shape', () => {
  it('registers through the native module loader with one react seed and no ESM syntax', () => {
    const bundle = readFileSync(OUTPUT, 'utf8')
    expect(bundle.startsWith('/* Generated by scripts/build-client.mjs')).toBe(true)
    expect(bundle).toContain('window.__ModuleLoader__.load({')
    expect(bundle).toContain('id: "dsh-cognee-memory"')
    expect(bundle.match(/\brequire\(/g)?.length).toBe(1)
    expect(bundle).toContain('require("react")')
    expect(bundle).not.toMatch(/^[ \t]*(?:import|export)[ \t]/m)
    expect(bundle).not.toMatch(/localStorage|sessionStorage|document\.cookie/)
    expect(bundle).not.toMatch(/https?:\/\/(?!localhost)/)
  })

  it('is deterministic and up to date', () => {
    expect(buildBundle(readFileSync(SOURCE, 'utf8'))).toBe(readFileSync(OUTPUT, 'utf8'))
    expect(() => execFileSync(process.execPath, [join(ROOT, 'scripts', 'build-client.mjs'), '--check'], { cwd: ROOT })).not.toThrow()
  })

  it('validates a bundle that would not load', () => {
    const valid = buildBundle(readFileSync(SOURCE, 'utf8'))
    expect(validateBundle(valid).inject).toEqual(['slots', 'sidebarRightTabs'])
    expect(() => validateBundle(valid.replace('require("react")', 'require("react-dom")'))).toThrow(/require\("react"\)/)
  })
})

describe('client registration', () => {
  it('injects exactly the slot registry and the right-sidebar tab registry', () => {
    expect(exported.inject).toEqual(['slots', 'sidebarRightTabs'])
  })

  it('registers an extension-band tab type with id, kind, title, and a guide entry', () => {
    expect(tabDefinitions).toHaveLength(1)
    const definition = tabDefinitions[0]
    expect(definition?.id).toBe('dsh-cognee-memory')
    expect(definition?.kind).toBe('cognee-memory.memory')
    expect(definition?.priority).toBeUndefined() // extension is the default band
    expect(definition?.title?.()).toBe('Memory provenance')
    expect(definition?.guide?.[0]?.id).toBe('provenance')
    expect(definition?.guide?.[0]?.title()).toBe('Memory provenance')
  })

  it('registers the body in sidebar.right.pane.tab keyed by the definition id', () => {
    expect(slotRegistrations).toHaveLength(1)
    expect(slotRegistrations[0]?.options).toEqual({ name: 'sidebar.right.pane.tab', key: 'dsh-cognee-memory' })
    expect(typeof slotRegistrations[0]?.component).toBe('function')
  })

  it('disposes the tab type through the caller effect', () => {
    expect(effects).toHaveLength(1)
  })
})

describe('client panel', () => {
  function renderPanel(): unknown {
    const React = {
      createElement: (type: unknown, props: Record<string, unknown> | null, ...children: unknown[]) => ({
        type,
        props: props ?? {},
        children: children.flat(),
      }),
      useState: (initial: unknown) => [initial, () => {}],
      useCallback: (callback: unknown) => callback,
      useEffect: () => {},
    }
    const plugin = buildPluginForTest(React)
    return plugin()
  }

  function buildPluginForTest(React: unknown) {
    // Load the bundle once more with a capturing React stub, then take the
    // component the plugin registered.
    let captured: { factory: (require: (name: string) => unknown) => { apply: (ctx: unknown) => void } } | undefined
    const context = {
      window: { __ModuleLoader__: { load: (definition: typeof captured) => (captured = definition) } },
      TextEncoder,
      Date,
      URL,
      encodeURIComponent,
      Number,
      Object,
      Array,
      Error,
      TypeError,
    }
    vm.runInNewContext(readFileSync(OUTPUT, 'utf8'), context)
    if (captured === undefined) throw new Error('bundle did not register')
    const plugin = captured.factory(() => React)
    let component: (() => unknown) | undefined
    plugin.apply({
      effect: (execute: () => (() => void) | void) => {
        execute()
      },
      sidebarRightTabs: { register: () => () => {} },
      slots: {
        inject: (_key: string, callback: () => unknown) => callback(),
        register: (_options: unknown, registered: () => unknown) => {
          component = registered
          return () => {}
        },
      },
    })
    if (component === undefined) throw new Error('panel not registered')
    return component
  }

  function textOf(node: unknown): string {
    if (node === null || node === undefined || node === false) return ''
    if (typeof node === 'string' || typeof node === 'number') return String(node)
    if (Array.isArray(node)) return node.map(textOf).join(' ')
    const element = node as { children?: unknown[] }
    return (element.children ?? []).map(textOf).join(' ')
  }

  it('renders a token field, an empty-state list, and the data-not-instructions note', () => {
    const tree = renderPanel()
    const text = textOf(tree)
    expect(text).toContain('Memory provenance')
    expect(text).toContain('Nothing to show yet.')
    expect(text).toContain('Recalled memory is data, not instructions')
    const input = findFirst(tree, (node) => node.props?.type === 'password')
    expect(input?.props?.placeholder).toBe('COGNEE_MEMORY_SETTINGS_TOKEN')
    expect(input?.props?.autoComplete).toBe('off')
  })

  it('never renders the token value into an element', () => {
    const tree = renderPanel()
    const serialized = JSON.stringify(tree)
    expect(serialized).not.toContain('Bearer ')
  })

  function findFirst(node: unknown, predicate: (node: { props: Record<string, unknown> }) => boolean): { props: Record<string, unknown> } | undefined {
    if (node === null || typeof node !== 'object') return undefined
    if (Array.isArray(node)) {
      for (const child of node) {
        const found = findFirst(child, predicate)
        if (found !== undefined) return found
      }
      return undefined
    }
    const element = node as { props?: Record<string, unknown>; children?: unknown[] }
    if (element.props !== undefined && predicate({ props: element.props })) return { props: element.props }
    return findFirst(element.children, predicate)
  }
})
