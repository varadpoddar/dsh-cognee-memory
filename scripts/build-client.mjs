#!/usr/bin/env node
/**
 * Deterministic native client-bundle builder.
 *
 * No bundler, TypeScript compiler, network, or package install: the browser
 * half is import-free ESM (`src/client/index.js`) and is inlined into the lazy
 * factory shape the DSH Web module loader expects
 * (`window.__ModuleLoader__.load({ id, factory })`). `react` is the only
 * module-table seed; there is no duplicate React, no CDN script, and no build
 * timestamp, so the output is byte-stable.
 *
 * Usage:
 *   node scripts/build-client.mjs           write lib/client.js
 *   node scripts/build-client.mjs --check   verify lib/client.js is current
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import vm from 'node:vm'
import { fileURLToPath } from 'node:url'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const SOURCE = path.join(ROOT, 'src', 'client', 'index.js')
const OUTPUT = path.join(ROOT, 'lib', 'client.js')
const PACKAGE_NAME = 'dsh-cognee-memory'

/** Remove the export syntax of the controlled module subset this source uses. */
export function stripExports(source) {
  const body = source
    .replace(/\r\n/g, '\n')
    .replace(/^([ \t]*)export[ \t]+(const|function|class)[ \t]+/gm, '$1$2 ')
  if (/^[ \t]*(?:import|export)[ \t]/m.test(body)) {
    throw new Error('src/client/index.js must not use ESM import/export beyond top-level const/function/class exports')
  }
  return body
}

/** Compose the module-table factory around the stripped source. */
export function buildBundle(source) {
  const body = stripExports(source)
  return `/* Generated by scripts/build-client.mjs from src/client/index.js. Do not edit. */
window.__ModuleLoader__.load({
  id: ${JSON.stringify(PACKAGE_NAME)},
  factory: (require) => {
    const module = { exports: {} }
    const exports = module.exports
    const React = require("react")
${body
  .split('\n')
  .map((line) => (line === '' ? '' : `    ${line}`))
  .join('\n')}
    const plugin = createPlugin({ React })
    exports.apply = plugin.apply
    exports.inject = plugin.inject
    return module.exports
  },
})
`
}

/** Fail loudly on a bundle that cannot load in the shell's module table. */
export function validateBundle(bundle) {
  if (!bundle.includes('window.__ModuleLoader__.load({')) {
    throw new Error('bundle must register through window.__ModuleLoader__.load')
  }
  if (!bundle.includes(`id: ${JSON.stringify(PACKAGE_NAME)}`)) {
    throw new Error(`bundle factory id must be ${JSON.stringify(PACKAGE_NAME)}`)
  }
  const requires = bundle.match(/\brequire\(/g) ?? []
  if (requires.length !== 1 || !bundle.includes('require("react")')) {
    throw new Error(`bundle must contain exactly one require("react"); found ${requires.length} require calls`)
  }
  if (/^[ \t]*(?:import|export)[ \t]/m.test(bundle)) {
    throw new Error('bundle still contains ESM import/export syntax')
  }
  if (/https?:\/\/(?!localhost)/.test(bundle.replace(/var\(--[^)]*\)/g, ''))) {
    throw new Error('bundle must not reference remote origins')
  }
  let loaded
  const sandbox = {
    window: {
      __ModuleLoader__: {
        load(definition) {
          loaded = definition
        },
      },
    },
    TextEncoder,
    Date,
    URL,
    encodeURIComponent,
    decodeURIComponent,
    Number,
    Math,
    JSON,
    Set,
    Map,
    Array,
    Object,
    String,
    Boolean,
    Error,
    TypeError,
  }
  vm.runInNewContext(bundle, sandbox, { timeout: 5_000 })
  if (loaded === undefined) throw new Error('bundle did not call window.__ModuleLoader__.load')
  if (loaded.id !== PACKAGE_NAME) throw new Error('bundle factory id mismatch')
  const reactStub = {
    createElement: () => null,
    useState: (initial) => [initial, () => {}],
    useCallback: (callback) => callback,
    useEffect: () => {},
    Fragment: 'Fragment',
  }
  const exported = loaded.factory((name) => {
    if (name !== 'react') throw new Error(`unexpected module-table request: ${name}`)
    return reactStub
  })
  if (typeof exported.apply !== 'function') throw new Error('bundle must export apply()')
  if (!Array.isArray(exported.inject)) throw new Error('bundle must export inject[]')
  return exported
}

function main() {
  const check = process.argv.includes('--check')
  const source = readFileSync(SOURCE, 'utf8')
  const bundle = buildBundle(source)
  validateBundle(bundle)
  if (check) {
    if (!existsSync(OUTPUT)) throw new Error('lib/client.js is missing; run node scripts/build-client.mjs')
    const current = readFileSync(OUTPUT, 'utf8')
    if (current !== bundle) throw new Error('lib/client.js is stale; run node scripts/build-client.mjs')
    process.stdout.write('client bundle up to date\n')
    return
  }
  mkdirSync(path.dirname(OUTPUT), { recursive: true })
  writeFileSync(OUTPUT, bundle, 'utf8')
  process.stdout.write(`built lib/client.js (${Buffer.byteLength(bundle)} bytes)\n`)
}

if (process.argv[1] !== undefined && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    main()
  } catch (error) {
    process.stderr.write(`${error instanceof Error ? error.message : String(error)}\n`)
    process.exitCode = 1
  }
}
