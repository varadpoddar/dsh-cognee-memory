#!/usr/bin/env node
/**
 * Milestone 11 report renderer.
 *
 *   node tests/eval/render-report.mjs --in report-part1.json --in extra.json \
 *        [--out docs/EVALUATION.md]
 *
 * Reads one or more JSON fragments (same schema, merged in order), prints
 * markdown to stdout or writes it to --out. Every number printed comes from the
 * input; nothing is invented. Exit code 2 on malformed input.
 */
import fs from 'node:fs'

const argv = process.argv.slice(2)
const inputs = []
let outPath = null
for (let i = 0; i < argv.length; i += 1) {
  if (argv[i] === '--in') inputs.push(argv[++i])
  else if (argv[i] === '--out') outPath = argv[++i]
  else if (argv[i] === '--help' || argv[i] === '-h') {
    console.log('usage: node tests/eval/render-report.mjs --in <json> [--in <json>...] [--out <md>]')
    process.exit(0)
  } else {
    fail(`unknown argument: ${argv[i]}`)
  }
}
if (inputs.length === 0) fail('at least one --in <json> is required')

function fail(message) {
  console.error(`render-report: ${message}`)
  process.exit(2)
}

function readJson(file) {
  let text
  try {
    text = fs.readFileSync(file, 'utf8')
  } catch (error) {
    fail(`cannot read ${file}: ${error.code ?? error.message}`)
  }
  try {
    return JSON.parse(text)
  } catch (error) {
    fail(`invalid JSON in ${file}: ${error.message}`)
  }
}

const fragments = inputs.map(readJson)
const scenarios = []
const notes = []
let runId = ''
let generatedAt = ''
const environment = {}
const metricSources = []

for (const fragment of fragments) {
  if (typeof fragment !== 'object' || fragment === null) fail('fragment is not an object')
  if (fragment.runId !== undefined) {
    if (runId !== '' && runId !== fragment.runId) fail(`runId mismatch: ${runId} vs ${fragment.runId}`)
    runId = fragment.runId
  }
  if (fragment.generatedAt !== undefined) generatedAt = generatedAt === '' ? fragment.generatedAt : generatedAt
  Object.assign(environment, fragment.environment ?? {})
  if (!Array.isArray(fragment.scenarios)) fail('fragment.scenarios must be an array')
  for (const scenario of fragment.scenarios) {
    if (typeof scenario?.id !== 'string' || typeof scenario.title !== 'string') fail('scenario needs id and title')
    if (!['PASS', 'FAIL', 'BLOCKED', 'SKIP'].includes(scenario.status)) fail(`bad status for ${scenario.id}`)
    scenarios.push(scenario)
  }
  if (fragment.metrics !== undefined && typeof fragment.metrics === 'object' && fragment.metrics !== null) {
    metricSources.push(fragment.metrics)
  }
  for (const note of fragment.notes ?? []) notes.push(note)
}

const metrics = Object.assign({}, ...metricSources)

function cell(text) {
  return String(text ?? '')
    .replace(/\r?\n+/g, ' ')
    .replace(/\|/g, '\\|')
    .trim()
}

function fence(text) {
  const body = String(text ?? '').replace(/\s+$/, '')
  if (body.split('\n').some((line) => line.trim() === '```')) return `\`\`\`\`text\n${body}\n\`\`\`\``
  return `\`\`\`text\n${body}\n\`\`\``
}

function percent(value) {
  return `${(value * 100).toFixed(1)}%`
}

function ms(value) {
  return `${Number(value).toFixed(1)} ms`
}

function metricRows() {
  const rows = []
  const first = metrics.firstTurnRecall
  if (first) rows.push(['First-turn recall success rate', `${first.successes}/${first.attempts} (${percent(first.rate)})`, 'fresh process per question, first turn'])
  const latency = metrics.recallLatencyMs
  if (latency) rows.push(['Recall latency p50 / p95', `${ms(latency.p50)} / ${ms(latency.p95)}`, `n=${latency.n}, max ${ms(latency.max)}`])
  const write = metrics.writeToRetrievableMs
  if (write) rows.push(['Write-to-retrievable latency p50 / p95', `${ms(write.p50)} / ${ms(write.p95)}`, `n=${write.n}, max ${ms(write.max)}`])
  const dupes = metrics.duplicateRate
  if (dupes) rows.push(['Duplicate rate', `${percent(dupes.rate)}`, `${dupes.duplicates} extra record(s) for ${dupes.writes} identical harness writes`])
  const leak = metrics.crossScopeLeakage
  if (leak) rows.push(['Cross-scope leakage rate', `${percent(leak.rate)}`, `${leak.leaks} leak(s) in ${leak.probes} probes`])
  const tokens = metrics.injectedTokenOverhead
  if (tokens) rows.push(['Injected-token overhead', `${tokens.last} tokens (last), p95 ${tokens.p95}`, `limit ${tokens.limit} tokens (stable 300 + query 900)`])
  const baseline = metrics.noMemoryBaseline
  if (baseline) rows.push(['No-memory baseline', `${baseline.withMemoryCorrect}/${baseline.questions} with memory vs ${baseline.withoutMemoryCorrect}/${baseline.questions} without`, 'planted questions answerable only from memory'])
  return rows
}

const lines = []
lines.push('# Milestone 11 — evaluation')
lines.push('')
lines.push(`Run \`${runId}\`, generated ${generatedAt}. Generated by \`tests/eval/\`; every number below is read from the run's JSON, not estimated.`)
lines.push('')
if (Object.keys(environment).length > 0) {
  lines.push('## Environment')
  lines.push('')
  lines.push('| Component | Value |')
  lines.push('| --- | --- |')
  for (const [key, value] of Object.entries(environment)) lines.push(`| ${cell(key)} | ${cell(value)} |`)
  lines.push('')
}

lines.push('## Method')
lines.push('')
lines.push('- Every scenario ran against the live deployment (Cognee `1.6.10-local`, EBAC on) with the shipped plugin; no mocks.')
lines.push('- Each recall question ran in a **fresh `dsh headless` process** with a `--patch` overlay that isolates the project scope; wall-clock milliseconds include process start and model time.')
lines.push("- Adapter-level latency used the plugin's own `CogneeRestAdapter` (n=20 queries) and its write/ingestion gate, not a synthetic HTTP client.")
lines.push('- The no-memory baseline used the same five questions with the plugin disabled (`enabled: false`), in one process, and counted how many planted codes appeared.')
lines.push('- Scenarios that change deployment state (service restart, container restart) are named in their evidence and leave the deployment restored.')
lines.push('- A scenario is `BLOCKED` only when the environment cannot produce the condition; `SKIP` is an explicit deferral.')
lines.push('')

lines.push('## Scenario results')
lines.push('')
lines.push('| # | Scenario | Result | Evidence |')
lines.push('| --- | --- | --- | --- |')
for (const scenario of scenarios) {
  const result = scenario.status === 'SKIP' ? 'SKIP' : `**${scenario.status}**`
  lines.push(`| ${cell(scenario.id)} | ${cell(scenario.title)} | ${result} | ${cell(scenario.summary)} |`)
}
lines.push('')

for (const scenario of scenarios) {
  const evidenceLines = String(scenario.evidence ?? '').split('\n').filter((line) => line.trim() !== '')
  const excerpt = evidenceLines.slice(0, 2).join('\n')
  if (excerpt === '') continue
  lines.push(`### ${scenario.id} — ${scenario.title}`)
  lines.push('')
  lines.push(`**${scenario.status}.** ${scenario.summary ?? ''}`.trim())
  lines.push('')
  if (Array.isArray(scenario.commands) && scenario.commands.length > 0) {
    lines.push('Commands:')
    lines.push('')
    lines.push(fence(scenario.commands.join('\n')))
    lines.push('')
  }
  lines.push('Raw excerpt (≤2 lines):')
  lines.push('')
  lines.push(fence(excerpt + (evidenceLines.length > 2 ? '\n…' : '')))
  lines.push('')
}

lines.push('## Metrics')
lines.push('')
lines.push('| Metric | Value | Basis |')
lines.push('| --- | --- | --- |')
for (const row of metricRows()) lines.push(`| ${cell(row[0])} | ${cell(row[1])} | ${cell(row[2])} |`)
lines.push('')

lines.push('## Exact commands')
lines.push('')
lines.push(fence([
  `su -c 'set -a; . /etc/dsh/cognee.env; . /etc/dsh/llm.env; set +a; node tests/eval/run-eval.mjs --run-id ${runId} --plugin-dir /var/lib/deepseek-harness/.dsh/profiles/headless/node_modules/dsh-cognee-memory/lib --work-dir /tmp/m11-eval --out /tmp/m11-eval/report-part1.json'  (on CT 103)`,
  `DSH_SSH_KEY=~/.ssh/dsh node tests/eval/check-backend-restart.mjs --run-id ${runId} --out /tmp/m11-eval/report-backend-restart.json`,
  `node tests/eval/render-report.mjs --in /tmp/m11-eval/report-part1.json --in /tmp/m11-eval/report-backend-restart.json --out docs/EVALUATION.md`,
  'dsh --profile headless --patch /tmp/m11-eval/patch-base.yml headless --json "<question>"',
  'systemctl restart deepseek-harness',
  'pct exec 106 -- docker restart cognee',
].join('\n')))
lines.push('')

if (notes.length > 0) {
  lines.push('## Notes')
  lines.push('')
  for (const note of notes) lines.push(`- ${String(note).replace(/\s+/g, ' ').trim()}`)
  lines.push('')
}

const markdown = `${lines.join('\n').replace(/\n{3,}/g, '\n\n').trimEnd()}\n`
if (outPath === null) process.stdout.write(markdown)
else {
  fs.writeFileSync(outPath, markdown)
  console.log(`wrote ${outPath} (${markdown.length} bytes, ${scenarios.length} scenarios)`)
}
